function pointInFlatRing(x: number, z: number, ring: readonly number[]): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    const xi = ring[i], zi = ring[i + 1];
    const xj = ring[j], zj = ring[j + 1];
    if ((zi > z) !== (zj > z) && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) inside = !inside;
  }
  return inside;
}

function minDistSqToRing(x: number, z: number, ring: readonly number[]): number {
  let best = Infinity;
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    const ax = ring[j], az = ring[j + 1];
    const bx = ring[i], bz = ring[i + 1];
    const dx = bx - ax, dz = bz - az;
    const len2 = dx * dx + dz * dz;
    const t = len2 > 1e-6 ? Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / len2)) : 0;
    const ex = x - (ax + dx * t), ez = z - (az + dz * t);
    const d2 = ex * ex + ez * ez;
    if (d2 < best) best = d2;
  }
  return best;
}

/** True when (x, z) lies strictly inside Lake Yogo water (excluding interior islets). */
export function inYogoLake(x: number, z: number): boolean {
  if (x < YOGO_BOUNDS[0] || x > YOGO_BOUNDS[2] || z < YOGO_BOUNDS[1] || z > YOGO_BOUNDS[3]) return false;
  if (!pointInFlatRing(x, z, LAKE_YOGO_OUTER)) return false;
  for (const hole of LAKE_YOGO_HOLES) if (pointInFlatRing(x, z, hole)) return false;
  return true;
}

/**
 * Carve a clean lakebed below YOGO_WATER_LEVEL inside the surveyed z15 shoreline and smoothly
 * feather the surrounding 34 m bank so coarse 200 m mountainside slopes never notch the shore.
 */
export function applyYogoLakebed(x: number, z: number, rawHeight: number): number {
  const pad = 34;
  if (x < YOGO_BOUNDS[0] - pad || x > YOGO_BOUNDS[2] + pad || z < YOGO_BOUNDS[1] - pad || z > YOGO_BOUNDS[3] + pad) {
    return rawHeight;
  }
  if (inYogoLake(x, z)) return Math.min(rawHeight, YOGO_WATER_LEVEL - 0.55);
  const d2 = minDistSqToRing(x, z, LAKE_YOGO_OUTER);
  if (d2 >= pad * pad) return rawHeight;
  const u = Math.sqrt(d2) / pad;
  const smooth = u * u * (3 - 2 * u);
  const edgeTarget = Math.min(rawHeight, YOGO_WATER_LEVEL + 0.15);
  return edgeTarget + (rawHeight - edgeTarget) * smooth;
}
