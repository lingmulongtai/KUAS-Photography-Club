"""Write src/scripts/hero/landmark-outlines.ts from OpenStreetMap (© OpenStreetMap contributors, ODbL).

Footprints, water bodies and roller-coaster centrelines for the hand-modelled Osaka and Nara
landmarks: Abeno Harukas, Tsutenkaku, Universal Studios Japan and the Heijo Palace site.
Coaster ways carry OSM `layer` only, so the viewer derives a smooth height profile from it.

    python tools/kansai-data/build_landmark_outlines.py [--cache DIR]
"""
import argparse
import json
import time
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'src/scripts/hero/landmark-outlines.ts'
API = 'https://overpass-api.de/api/interpreter'
# name -> OSM way id. Every way is checked against its name/tags below.
OUTLINES = {
    'harukasSite': (187296989, 'あべのハルカス'),
    'harukasTower': (488467176, 'タワー館'),
    'harukasWing': (602589263, 'ウイング館'),
    'tsutenkaku': (254319878, '通天閣'),
    'hogwarts': (1302390506, 'ホグワーツ城'),
    'usjLagoon': (312246806, None),
    'usjBlackLake': (501233718, '黒い湖'),
    'usjPond': (310668079, None),
    'daigokuden': (105145325, '第一次大極殿'),
    'daigokumon': (1423223776, '大極門'),
    'toro': (1423223774, '東楼'),
    'seiro': (1499247887, '西楼工事建屋'),
    'daigokudenIn': (378258845, '第一次大極殿院'),
    'suzakumon': (378251094, '朱雀門'),
    'kentoshiShip': (1499252414, '復元遣唐使船'),
    'toinPond1': (919973814, None),
    'toinPond2': (919973816, None),
    'toinPond3': (919973837, None),
    'toinPond4': (919973851, None),
}
COASTER_BOXES = {
    # Clusters of connected `roller_coaster=track` ways, by the area each ride occupies.
    'hollywoodDream': (34.6650, 135.4320, 34.6678, 135.4366),
    'flyingDinosaur': (34.6628, 135.4294, 34.6660, 135.4315),
    'hippogriff': (34.6680, 135.4316, 34.6690, 135.4325),
    'mineCart': (34.6683, 135.4300, 34.6695, 135.4311),
}


def overpass(query, cache, name):
    path = cache / (name + '.json') if cache else None
    if path and path.exists():
        return json.loads(path.read_text(encoding='utf-8'))
    for wait in (0, 30, 60, 120):
        time.sleep(wait)
        request = Request(API, data=urlencode({'data': query}).encode(),
                          headers={'User-Agent': 'kuas-hero-landmark-outlines/1.0'})
        try:
            with urlopen(request, timeout=200) as response:
                data = json.load(response)
            break
        except Exception as error:  # Overpass answers 429/504 when busy.
            print('retrying Overpass', error)
    else:
        raise RuntimeError('Overpass unavailable')
    if path:
        path.write_text(json.dumps(data), encoding='utf-8')
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path)
    args = parser.parse_args()
    if args.cache:
        args.cache.mkdir(parents=True, exist_ok=True)
    ids = ','.join(str(i) for i, _ in OUTLINES.values())
    query = (f'[out:json][timeout:120];(way(id:{ids});way["roller_coaster"="track"]'
             '(34.660,135.425,34.671,135.440););out body;>;out skel qt;')
    data = overpass(query, args.cache, 'landmark-outlines')
    nodes = {e['id']: (e['lat'], e['lon']) for e in data['elements'] if e['type'] == 'node'}
    ways = {e['id']: e for e in data['elements'] if e['type'] == 'way'}
    lines = ['// Generated by tools/kansai-data/build_landmark_outlines.py. Do not edit.',
             '// © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).',
             '/** Closed outlines as flat [lat, lon, …] lists; the last point repeats the first. */',
             'export const OUTLINES = {']
    for key, (way_id, name) in OUTLINES.items():
        way = ways[way_id]
        if name and way.get('tags', {}).get('name') != name:
            raise ValueError(f'OSM way {way_id} is no longer {name}')
        flat = [round(v, 7) for n in way['nodes'] for v in nodes[n]]
        lines.append(f'  {key}: {json.dumps(flat)}, // way {way_id}')
    lines += ['} as const;', '',
              '/** Coaster centrelines: each way as [lat, lon, …] with its OSM layer. */',
              'export const COASTERS = {']
    tracks = [w for w in ways.values() if w.get('tags', {}).get('roller_coaster') == 'track']
    for key, (south, west, north, east) in COASTER_BOXES.items():
        lines.append(f'  {key}: [')
        for way in sorted(tracks, key=lambda w: w['id']):
            pts = [nodes[n] for n in way['nodes']]
            lat = sum(p[0] for p in pts) / len(pts)
            lon = sum(p[1] for p in pts) / len(pts)
            if not (south <= lat <= north and west <= lon <= east):
                continue
            flat = [round(v, 7) for p in pts for v in p]
            layer = int(way['tags'].get('layer', 0))
            lines.append(f'    {{layer: {layer}, points: {json.dumps(flat)}}}, // way {way["id"]}')
        lines.append('  ],')
    lines += ['} as const;', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
